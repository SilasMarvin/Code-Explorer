/// Whether `name` is a common standard library method.
pub(crate) fn is_std_method(name: &str) -> bool {
    NAMES.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_sorted_and_found() {
        assert!(NAMES.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(is_std_method("map") && is_std_method("zip") && is_std_method("abs"));
        assert!(!is_std_method("tile_point"));
    }
}
